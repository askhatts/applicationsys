def seed_all(db):
    for i, (grp, name) in enumerate(DEPARTMENTS):
        db.execute(
            "INSERT INTO departments (name, grp, sort_order) VALUES (?, ?, ?)",
            (name, grp, i),
        )
    for name in SERVICES:
        db.execute("INSERT INTO services (name) VALUES (?)", (name,))
    for i, (name, service_name) in enumerate(CATEGORIES):
        db.execute(
            "INSERT INTO categories (name, service_id, sort_order) "
            "VALUES (?, (SELECT id FROM services WHERE name = ?), ?)",
            (name, service_name, i),
        )
    for i, (name, hours) in enumerate(PRIORITIES):
        db.execute(
            "INSERT INTO priorities (name, sla_hours, sort_order) VALUES (?, ?, ?)",
            (name, hours, i),
        )
    for key, value in SETTINGS.items():
        db.execute("INSERT INTO settings (key, value) VALUES (?, ?)", (key, value))
    db.execute(
        "INSERT INTO settings (key, value) VALUES ('dashboard_view_token', ?)",
        (secrets.token_urlsafe(16),),
    )
    db.commit()


def create_user(db, login, password, full_name, role, service_id=None):
    from werkzeug.security import generate_password_hash

    db.execute(
        "INSERT INTO users (login, password_hash, full_name, role, service_id, created_at) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (login, generate_password_hash(password), full_name, role, service_id, now_str()),
    )
    db.commit()
